-- ============================================================================
-- I-08 — 손실 상환의 과세 금융소득은 0이다
--
-- DOC-002 v0.3 §8, CLAUDE.md 절대 규칙 #8
--
-- DOC-002 v0.2까지 I-08은 "애플리케이션 레벨 검증"이었다. v0.3에서 그 분류를
-- 철회하고(U-03) DB 제약을 추가한다. DOC-011 §6 V-12의 계약 계층 검증을
-- 없애는 것이 아니라 역할을 나눈다 — DOC-010 §3.3이 RLS와 계약 계층에 이미
-- 적용한 구조와 같다.
--
--   계약 계층 (V-12) : 필드별 VALIDATION_FAILED 반환. UX 목적
--   DB CHECK        : 최종 보장. 우회 불가
--
-- 철회 사유는 단순하다. I-08은 단일 행 불변식이라 제약으로 표현할 수 있는데,
-- 동시에 절대 규칙 #8이며 세액에 직결된다. 프로젝트의 핵심 전제를 규율에만
-- 맡기는 것은 ADR-002가 선언한 "정합성을 규율이 아니라 구조로 보장한다"와
-- 어긋난다.
--
-- ★ 이 제약에 걸리는 상환이 나오면 제약을 풀지 않는다.
--
--   손실 상환에 과세소득이 붙는 구조(예: 기중 쿠폰을 지급하는 월지급식)가
--   등장하면, 제약이 틀린 것이 아니라 모델의 전제가 그 상품에 맞지 않는다는
--   신호다. 현재 모델은 상품당 상환 1건(I-01)에 과세소득 1개를 전제한다.
--   기중 지급이 있는 구조는 지급 이벤트가 여러 개이므로 redemptions 1건으로
--   표현할 수 없고, 상환과 별개의 지급 엔티티가 필요하다. 그때는 DQ-03과
--   같은 수준의 모델 변경으로 다룬다 — 제약 삭제로 넘기지 않는다.
-- ============================================================================

alter table public.redemptions
  add constraint redemptions_maturity_loss_check
  check (redemption_type <> 'MATURITY_LOSS' or taxable_income = 0);

comment on constraint redemptions_maturity_loss_check on public.redemptions is
  'I-08: 손실 상환의 과세 금융소득은 0이다. ELS 손실은 다른 금융소득과 통산되지 않으므로 음수도 양수도 될 수 없다(DOC-007 §4.4). 이 제약에 걸리는 상환이 나오면 제약이 아니라 모델을 고친다 — DOC-002 §8 참조.';
