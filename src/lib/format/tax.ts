/**
 * 고를 수 있는 연도 — **하한은 계약이 주고 상한은 화면이 정한다** (DOC-008 §5, §4.6 v1.9)
 *
 * ## 세 항이 서로 다른 곳에서 온다
 *
 * | 항 | 출처 | 왜 |
 * |---|---|---|
 * | 하한 | `seededYears[0]` | 그보다 과거는 계약이 **거부**하므로 제시하면 오류 화면으로 가는 선택지가 된다 |
 * | 연속 구간의 상한 | `max(기준일 연도, 마지막 시드 연도)` | 미래는 근사로 허용되지만 다년도 조망은 SCR-402의 일이다 |
 * | 보고 있는 연도 | `view.year` | 선택 상자가 그 값을 잃으면 「조회」가 다른 연도로 이동한다 |
 *
 * ## 셋째 항을 `Math.max`에 넣지 않는다 — 그러면 주소가 목록의 길이를 정한다
 *
 * v1.1까지 셋째 항이 상한 계산 안에 있었고 목록은 하한부터 **연속**이었다. 그래서
 * `?year=9999`가 `<option>` **7,974개**를 렌더했다 — 오류가 아니고 그럴싸한 화면이다.
 *
 * **자르는 대안은 더 나쁘다.** 「기준일 연도 + N으로 자른다」로 하면 (a) `N`이 어느
 * 문서에도 근거가 없는 상수가 되고 (b) **컨트롤이 조용히 거짓을 말하는 상태가
 * 되살아난다** — `<select defaultValue>`가 어느 `<option>`과도 맞지 않으면 비어 있는
 * 것이 아니라 **첫 항목을 고른 것처럼 보인다**(React가 `selected`를 붙이지 않고
 * 브라우저가 첫 항목을 고른다). 셋째 항이 애초에 추가된 이유가 정확히 그 상태를
 * 막는 것이었으므로, 자르면 문제를 원위치시킨다.
 *
 * **그래서 연속 구간에서 빼내 낱개로 덧붙인다.** 구간의 두 끝이 전부 데이터에서 오므로
 * (시드·기준일) 주소는 길이를 정할 수 없고, 목록의 크기는 `(구간) + 1`로 묶인다.
 * 구간과 떨어진 연도 하나가 보이는 것은 **의도된 모습**이다 — 그 상태는 주소를 손으로
 * 고쳤을 때만 생기고, 그때 화면은 실제로 그 연도를 계산하고 있으므로 선택지가 그
 * 사실과 일치해야 한다.
 *
 * ## 두 끝이 **모두** 데이터에서 온다 — 하한도 예외가 아니다
 *
 * 초안은 하한을 `Math.min(seeded[0], view.year)`로 두어 「거부가 사라지는 날 목록에
 * 없는 과거 연도가 거짓 표시를 만든다」를 막으려 했다. **그 방어가 같은 결함을 반대
 * 방향으로 만든다** — `year = 1000`을 그 식에 넣으면 구간이 `1000 … 2026`이 되어
 * 항목이 **1,027개**다(시드가 2026 하나인 현재 값. 이 파일의 테스트 픽스처는 시드를
 * 둘로 두므로 그쪽에서는 1,028이다). 상한에서 고친 것과 정확히 같은 형태이므로 하한도
 * 같은 방식으로 다룬다: 연속 구간은 `seeded[0] … max(기준일 연도, 마지막 시드 연도)`이고
 * **보고 있는 연도는 어느 쪽 밖이든 낱개로** 붙는다. 그러면 구간의 길이가 주소에
 * 의존하지 않으면서 컨트롤은 여전히 실제 연도를 가리킨다.
 *
 * > **이 수는 함수를 실행한 계산값이고 화면 실측이 아니다.** `?year=1000`은 `<option>`을
 * > **한 개도** 렌더하지 않는다 — `resolveTaxYear`가 시드 이전 연도에 `TaxSeedRangeError`를
 * > 던지고 화면이 이 함수를 부르기 **전에** 「범위 밖」 분기를 반환하기 때문이다(그 분기에는
 * > `<select>`가 없다). 상한 쪽의 7,974는 사정이 다르다 — 미래 연도는 계약이 근사로
 * > 허용하므로 그쪽은 실제로 렌더된다.
 *
 * 즉 하한 밖은 **현재 도달 불가**이며, 그래도 방어를 고치는 이유는 **방어가 자기가
 * 막으려는 결함을 만들어서는 안 된다**는 것이다.
 *
 * ## 전제: `seededYears`는 오름차순이다
 *
 * `seeded[0]`을 하한으로, 마지막 원소를 상한으로 읽으므로 내림차순 배열에서는
 * `first > last`가 되어 **구간이 통째로 사라진다**(오류 없이 목록이 낱개 하나가 된다).
 * 그 정렬은 조회 계층이 보장하며(`resolveTaxYear`가 질의의 `order`에 기대지 않고
 * 스스로 정렬한다) **이 모듈은 그것을 검사하지 않는다** — 순수 모듈로 뗀 이유가
 * 「계약 없이 검증된다」인데 전제가 계약 쪽에만 있다는 뜻이므로, 그 성질을 테스트에
 * 케이스로 고정해 둔다.
 */
export function selectableYears(
  view: { seededYears: readonly number[]; year: number; taxLawYear: number },
  currentYear: number,
): number[] {
  const seeded = view.seededYears
  // ★ 두 끝에 `view.year`가 들어가면 목록의 길이가 주소에서 온다(머리글).
  const first = seeded[0] ?? view.taxLawYear
  const last = Math.max(currentYear, seeded[seeded.length - 1] ?? first)

  const years: number[] = []
  for (let candidate = first; candidate <= last; candidate += 1) years.push(candidate)

  // 구간 밖이면 낱개로 — 위아래 어느 쪽이든. 정렬을 유지해 삽입한다.
  if (!years.includes(view.year)) {
    years.push(view.year)
    years.sort((a, b) => a - b)
  }

  return years
}
