import { dec } from '@/lib/decimal'

/**
 * 배리어 일괄 입력 — **SQ-04 해결** (DOC-008 §5 SCR-204, §9 SQ-04)
 *
 * 문서가 요구한 것은 「`90-85-80-75-70-65` 형식의 일괄 입력을 지원하고, 파싱 결과를
 * 차수별 표로 즉시 표시한다」이며 미결이던 것은 **구분자의 허용 범위**다.
 *
 * ## 결정 ① — 구분자는 「숫자와 점이 아닌 모든 연속」이다
 *
 * 목록을 열거하지 않는다(`-`·`/`·공백·쉼표·`|`·줄바꿈…). 열거하면 사용자가 적은
 * 어떤 글자가 목록 밖일 때 **그 글자가 숫자에 붙어 토큰이 된다** — `90 / 85`에서
 * 슬래시만 허용하면 `90 `과 ` 85`가 되거나 `90/85`가 한 토큰이 되고, 그 결과는
 * 「배리어는 2 이하여야 한다」 같은 고칠 수 없는 오류로 나타난다. 반대로 정의하면
 * 붙일 수 있는 구분자가 **전부** 동작하고, 남는 실패 형태는 「숫자가 아닌 것을
 * 적었다」 하나로 줄어든다.
 *
 * 부수 효과 하나가 이 정의를 확정한다: **음수 부호가 구분자로 흡수된다.**
 * `90-85`의 `-`가 뺄셈이나 음수로 읽히지 않으므로 문서의 예시가 그대로 동작한다.
 *
 * 대가는 **숫자를 품지 않은 오타가 사라진다**는 것이다 — `90-팔십오-80`은 두 건이
 * 된다. 값이 밀리지는 않고(사라진 자리가 아니라 개수가 줄어든다) 남는 신호는
 * 개수이며 그것을 세 곳이 본다: 안내 문구·차수표의 빈 칸·V-03(저장 시점).
 * 열거 방식이면 목록 밖의 글자가 숫자에 **붙어** `90팔십오`가 한 토큰이 되고
 * 그때는 값이 밀린다 — 더 나쁜 실패다.
 *
 * ## 결정 ② — 토큰 하나라도 2를 넘으면 전부 퍼센트로 읽는다
 *
 * 경계 2는 **V-08의 상한과 같은 값**이다(비율은 `x ≤ 2`). 그 위의 값은 비율일 수
 * 없으므로 퍼센트로만 해석되고, 2 이하는 둘 다 가능하다 — 그 모호함을 값마다 따로
 * 판정하면 `90-0.85-80`이 (0.9, 0.85, 0.8)로 읽혀 **사용자가 의도한 것과 우연히
 * 같아진다.** 우연히 맞는 해석은 다음 입력에서 틀리고, 틀렸을 때 원인이 입력이
 * 아니라 우리 추측에 있다.
 *
 * 그래서 목록 전체를 한 단위로 읽고 **어떻게 읽었는지 화면에 적는다.** 문서가
 * 「파싱 결과를 차수별 표로 즉시 표시」를 요구한 이유가 이것이며, 표만으로는
 * 부족하다 — `0.85`가 `0.85%`가 된 것은 표에 나타나지만 **왜** 그렇게 되었는지는
 * 해석 모드를 적어야 보인다.
 *
 * ## 결정 ③ — 검증하지 않는다
 *
 * 형식이 아닌 토큰은 **그대로 통과시킨다.** V-08의 문구는 계약 계층에서 나와야
 * 하고(`parse.ts` 머리글의 규칙), 그 토큰은 자기 차수의 칸에 남으므로 오류가 그
 * 칸에 붙는다. 여기서 버리면 차수가 밀려 **다른 차수의 배리어가 된다.**
 */

/** 숫자·점이 아닌 연속 = 구분자 */
const SEPARATOR = /[^\d.]+/

/** 비율·퍼센트로 읽을 수 있는 토큰. `.9`도 받는다(사람이 그렇게 적는다) */
const NUMERIC = /^(?:\d+(?:\.\d+)?|\.\d+)$/

/** V-08의 비율 상한. 이 값을 넘는 토큰은 비율일 수 없다 */
const RATIO_MAX = 2

export type BarrierList = {
  /**
   * 차수별 칸에 넣을 값 — **퍼센트**다.
   *
   * 폼의 모든 비율 칸이 퍼센트이므로(연쿠폰율·KI 배리어와 같은 단위) 여기서 단위를
   * 맞춘다. 소수로 넣으면 한 칸만 다른 단위가 되고, `percentToRatio`가 그 칸에서
   * 100으로 한 번 더 나눈다.
   */
  tokens: string[]
  /** 입력을 무엇으로 읽었는가. 화면이 이 값을 문구로 적는다 */
  readAs: 'PERCENT' | 'RATIO'
  /**
   * 퍼센트로 읽었는데 2 이하인 토큰이 섞여 있다 — **혼합 입력의 신호**.
   *
   * `90-0.85-80`이 그 형태이며 결과(`0.85%`)가 V-08을 통과하므로 계약이 잡지 못한다.
   * 표에 값이 보이더라도 「왜」가 없으면 오타로 읽히지 않으므로 화면이 경고한다.
   */
  mixed: boolean
}

export function parseBarrierList(raw: string): BarrierList {
  const pieces = raw
    .split(SEPARATOR)
    .map((piece) => piece.trim())
    .filter((piece) => piece !== '')

  const numeric = pieces.filter((piece) => NUMERIC.test(piece))
  const readAs = numeric.some((piece) => dec(piece).gt(RATIO_MAX)) ? 'PERCENT' : 'RATIO'

  const tokens = pieces.map((piece) => {
    if (!NUMERIC.test(piece)) return piece
    // 소수로 읽었으면 퍼센트로 옮긴다. **Decimal로 곱한다** — `0.885 × 100`이
    // float64에서 `88.50000000000001`이 되는 부류이고 린트가 이 디렉터리에서
    // 강제 변환을 막는다.
    return readAs === 'PERCENT' ? piece : dec(piece).mul(100).toString()
  })

  return {
    tokens,
    readAs,
    mixed:
      readAs === 'PERCENT' && numeric.some((piece) => dec(piece).lte(RATIO_MAX)),
  }
}

/**
 * 해석 결과를 사용자에게 적는다 — **차수표만으로는 부족하다**
 *
 * 표는 `0.85`가 `0.85%`가 되었다는 **사실**을 보여주고 이 문구는 **이유**를 말한다.
 * 오류가 아니므로 `FormState.status`를 바꾸지 않는다(안내다).
 */
export function barrierNotice(list: BarrierList, rounds: number): string {
  const parts: string[] = []

  parts.push(
    list.readAs === 'PERCENT'
      ? `배리어 ${list.tokens.length}건을 퍼센트로 읽었다.`
      : `배리어 ${list.tokens.length}건을 소수로 읽어 퍼센트로 바꿨다 (0.9 → 90).`,
  )

  if (rounds > 0 && rounds !== list.tokens.length) {
    parts.push(`총 차수 ${rounds}과 개수가 다르다 — 차수표를 확인한다.`)
  }
  if (list.mixed) {
    parts.push(
      '2 이하인 값이 섞여 있다 — 퍼센트로 읽었으므로 0.85는 0.85%가 된다. 단위를 통일한다.',
    )
  }

  return parts.join(' ')
}
