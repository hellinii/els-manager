import { describe, expect, it } from 'vitest'

import { selectableYears } from '@/lib/format'

/**
 * SCR-401 연도 선택지 — **주소가 목록의 길이를 정하지 않는다** (P4.5)
 *
 * ## 이 파일이 생긴 이유
 *
 * 이 산출은 v1.1까지 `app/(app)/tax/page.tsx` 안에 있었고, 그 파일은 `server.ts`를
 * 끌어오므로 **어떤 스위트의 import 그래프에도 들어갈 수 없다**(DOC-010 AQ-23). 그
 * 동안 `?year=9999`가 `<option>` **7,974개**를 렌더하는 상태가 아무 층에서도
 * 관측되지 않았다. 순수 모듈로 옮긴 만큼이 여기서 보인다.
 *
 * ## 자르지 않고 연속 구간에서 빼낸다
 *
 * 「기준일 연도 + N으로 자른다」를 버린 이유가 이 파일의 케이스 하나로 고정된다 —
 * 자르면 보고 있는 연도가 목록에서 사라지고, `<select defaultValue>`가 어느
 * `<option>`과도 맞지 않으면 **비어 있는 것이 아니라 첫 항목을 고른 것처럼 보인다.**
 * 그것이 셋째 항을 애초에 추가한 이유(컨트롤이 조용히 거짓을 말한다)와 같은 상태다.
 * 그래서 구간의 두 끝은 데이터에서만 오고(시드·기준일) 보고 있는 연도는 **낱개**로
 * 붙는다.
 *
 * ## 음성 대조 4건 — 넷이 각각 다른 집합을 잡는다
 *
 * | 되돌린 것 | 실패한 케이스 |
 * |---|---|
 * | `view.year`를 `Math.max`에 되돌림(v1.1 형태) | **2건** — 조작된 미래 연도 · 시드가 비면 |
 * | 낱개 덧붙임 제거 | **5건** — 조작된 미래 연도 · 반드시 포함한다 · 하한 밖 · 시드가 비면 · 내림차순 |
 * | `last = currentYear`(시드 상한 무시) | **3건** — 시드가 기준일보다 미래 · 조작된 미래 연도 · 하한 밖 |
 * | 하한을 `Math.min(seeded[0], view.year)`로 되돌림(초안 형태) | **1건** — 하한 밖뿐 |
 *
 * 첫 줄이 이 파일의 기록이다 — v1.1 형태에서 **「반드시 포함한다」는 통과한다**(7,974개
 * 목록에도 그 연도가 있다). 즉 **길이 단언이 그 결함을 잡는 유일한 대조점**이며, 그것이
 * 없으면 결함이 있는 구현이 아무 단언도 깨뜨리지 않는다. 마지막 줄이 **1건**인 것도 같은
 * 형태다 — 하한 케이스가 그 변형의 유일한 대조점이다.
 *
 * > **이 표가 두 번 낡았다는 것을 기록한다.** 처음 측정한 뒤 하한 케이스를 추가하면서
 * > 앞 두 줄을 다시 돌리지 않아 「2건」이 「3건」으로 틀렸고(적대적 반증이 잡았다), 그것을
 * > 고치면서 폴백·내림차순 케이스를 함께 추가해 **다시** 두 줄이 틀렸다. 원인이 같다 —
 * > **표를 케이스보다 먼저 쓰고 케이스를 뒤에 더했다.** 규율은 하나다: 케이스를 더하거나
 * > 지우면 **네 줄을 전부 다시 돌린다.** 위 숫자는 그렇게 얻은 것이다.
 *
 * ## 무효 대조 세 유형을 순서대로 배제한다
 *
 * ① **픽스처가 두 구현에서 일치한다** — 시드와 기준일 연도가 같으면 `max`의 두 항이
 *    같은 답을 내고, 보고 있는 연도가 구간 안이면 낱개 덧붙임이 아무 일도 하지 않는다.
 *    그래서 **세 값을 서로 다르게** 둔 케이스를 각각 만든다(시드 > 기준일 / 보고 있는
 *    연도 > 둘 다 / 구간 안).
 * ② **테스트가 값을 얹는다** — 기대 배열을 손으로 적되 **길이를 함께 단언한다.**
 *    `toContain`만 쓰면 7,974개 목록도 통과하므로(원래 결함이 정확히 그 형태다) 그
 *    단언은 이 축에서 값을 얹는 것과 같다.
 * ③ **단언이 깨뜨림에 불변인 대리 지표를 본다** — 「목록이 비어 있지 않다」나
 *    「보고 있는 연도를 포함한다」만 보면 v1.1 형태가 **둘 다 통과한다**(7,974개 목록도
 *    비어 있지 않고 그 연도를 포함한다). 그래서 **길이와 원소를 함께** 본다.
 */

const SEEDED = [2026, 2027] as const

describe('연도 선택지', () => {
  it('★ 하한은 **첫 시드 연도**다 — 다른 세 값이 아니다', () => {
    /*
     * ★ **픽스처의 네 값을 서로 다르게 둔다.** 처음에는 전부 2026이었고 그러면
     * `years[0] === 2026`이 `first`가 `seeded[0]`·`taxLawYear`·`view.year`·`min(…)`
     * 어느 것이어도 참이라 **하한 구현의 어떤 변형도 잡지 못했다** — 적대적 반증이
     * 그 퇴화를 잡았다(무효 대조 ①: 픽스처가 두 구현에서 일치한다).
     *
     * 시드 하한 2026 · 보고 있는 연도 2027 · `taxLawYear` 2027 · 기준일 2028로 두면
     * 네 후보가 각각 다른 답을 낸다.
     */
    const years = selectableYears(
      { seededYears: SEEDED, year: 2027, taxLawYear: 2027 },
      2028,
    )
    expect(years[0]).toBe(2026)
    // 제시하면 오류 화면으로 가는 선택지가 된다(§4.6 v1.9의 근거) — 그러므로 하한이
    // 시드보다 내려가지 않는 것이 이 단언의 뜻이다.
    expect(years).toEqual([2026, 2027, 2028])
  })

  it('연속 구간의 상한은 `max(기준일 연도, 마지막 시드 연도)`다', () => {
    // 기준일이 시드보다 미래인 경우 — 미래 연도는 근사로 허용되므로 제시한다.
    expect(
      selectableYears({ seededYears: SEEDED, year: 2029, taxLawYear: 2027 }, 2029),
    ).toEqual([2026, 2027, 2028, 2029])
  })

  it('★ 시드가 기준일보다 미래면 시드까지 제시한다 — 두 항이 다른 곳에서 온다', () => {
    /*
     * ★ 이 케이스가 없으면 `Math.max(currentYear, lastSeeded)`를 `currentYear`로
     * 되돌린 구현이 통과한다. 2027년 세율 마이그레이션이 2026년에 들어오는 것은
     * 정상 경로이며(§5.6이 미래 연도 프로필 저장을 정상으로 규정한다) 그때 그 연도를
     * 고를 수 없으면 시드가 화면에 도달하지 않는다.
     */
    expect(
      selectableYears({ seededYears: SEEDED, year: 2026, taxLawYear: 2026 }, 2026),
    ).toEqual([2026, 2027])
  })

  it('★ 조작된 미래 연도가 목록의 길이를 정하지 않는다', () => {
    /*
     * ★ **이것이 P4.5가 고친 결함이다.** v1.1은 `view.year`를 상한 계산에 넣었고
     * 목록이 하한부터 연속이었으므로 `?year=9999`가 `<option>` 7,974개를 렌더했다.
     * 오류가 아니고 그럴싸한 화면이라 어느 층에서도 드러나지 않았다.
     *
     * 길이와 원소를 **함께** 단언한다 — 「9999를 포함한다」만 보면 결함이 있는 구현도
     * 통과한다(7,974개 목록에도 9999가 있다).
     */
    const years = selectableYears(
      { seededYears: SEEDED, year: 9999, taxLawYear: 2027 },
      2026,
    )
    expect(years).toEqual([2026, 2027, 9999])
    // 구간(2) + 낱개(1). 상한이 주소에서 오면 이 수가 7,974가 된다.
    expect(years).toHaveLength(3)
  })

  it('★ 보고 있는 연도를 반드시 포함한다 — 컨트롤이 거짓을 말하지 않는다', () => {
    /*
     * ★ `<select defaultValue>`가 어느 `<option>`과도 맞지 않으면 브라우저가 **첫
     * 항목**을 고른 것으로 보인다(비어 있지 않다). 그러면 사용자가 2035년을 보면서
     * 선택 상자에는 2026년이 있고, 「조회」를 누르는 순간 다른 연도로 이동한다.
     *
     * 자르는 대안을 버린 근거가 이 단언이다 — 자르면 여기가 빨간불이 된다.
     */
    for (const viewed of [2028, 2035, 3000]) {
      const years = selectableYears(
        { seededYears: SEEDED, year: viewed, taxLawYear: 2027 },
        2026,
      )
      expect(years, String(viewed)).toContain(viewed)
    }
  })

  it('구간 안의 연도는 낱개로 중복되지 않는다', () => {
    // 낱개 덧붙임이 `includes` 가드를 지나므로 2027이 두 번 나오지 않는다.
    const years = selectableYears(
      { seededYears: SEEDED, year: 2027, taxLawYear: 2027 },
      2027,
    )
    expect(years).toEqual([2026, 2027])
  })

  it('오름차순이다 — 낱개가 뒤에 붙어도', () => {
    const years = selectableYears(
      { seededYears: SEEDED, year: 4000, taxLawYear: 2027 },
      2026,
    )
    expect([...years].sort((a, b) => a - b)).toEqual(years)
  })

  it('★ 하한 밖의 연도도 낱개다 — 방어가 같은 결함을 반대 방향으로 만들지 않는다', () => {
    /*
     * ★ 초안은 하한을 `Math.min(seeded[0], view.year)`로 두었고 그 식에 `year = 1000`을
     * 넣으면 구간이 `1000 … 2026`이 되어 항목이 **1,027개**다(시드가 2026 하나인 현재
     * 값. 이 파일의 픽스처는 시드를 둘로 두므로 아래 단언에서는 1,028이 된다). 상한에서
     * 고친 것과 정확히 같은 형태이므로(목록의 길이가 주소에서 온다) 하한도 데이터에서만
     * 오게 했다.
     *
     * **이 수는 함수를 실행한 계산값이고 화면 실측이 아니다** — `?year=1000`은 `<option>`을
     * 한 개도 렌더하지 않는다(계약이 시드 이전 연도를 `TaxSeedRangeError`로 거부해 화면이
     * 이 함수를 부르기 전에 「범위 밖」 분기를 반환한다. 그 분기에는 `<select>`가 없다).
     * 상한 쪽 7,974는 사정이 달라 실제로 렌더된다 — 미래 연도는 근사로 허용되기 때문이다.
     *
     * 그래도 단언을 두는 이유는 **방어가 자기가 막으려는 결함을 만들지 않아야** 하기
     * 때문이다.
     */
    const years = selectableYears(
      { seededYears: SEEDED, year: 1000, taxLawYear: 2027 },
      2026,
    )
    expect(years).toEqual([1000, 2026, 2027])
    expect(years).toHaveLength(3)
  })

  it('★ 시드가 비면 `taxLawYear`가 하한이 된다 — 폴백에 민감한 단언이다', () => {
    /*
     * ★ 처음에는 `{ seededYears: [], year: 2026, taxLawYear: 2026 }`로 두고
     * `[2026]`을 기대했는데 **항진명제였다** — 폴백(`?? view.taxLawYear`)을 제거해도
     * 9건 전부 초록이었다. 이유가 측정 가능하다: `undefined <= NaN`이 거짓이라 루프가
     * **0회** 돌고(무한 루프가 아니다) 빈 배열이 된 뒤, **낱개 덧붙임**이 `view.year`를
     * 넣어 `[2026]`이 되어 기대값과 같아진다. 빈 배열을 막은 것은 폴백이 아니었다.
     *
     * 그래서 폴백이 **구간을 만드는 것**을 본다 — 보고 있는 연도를 폴백 밖에 두면
     * 결과가 「구간 하나 + 낱개 하나」가 되고, 폴백이 없으면 구간이 `NaN`으로 붕괴해
     * **낱개 하나만** 남는다. 실측으로 갈린다: `[2026, 2030]` vs `[2030]`.
     *
     * (도달하지 않아야 하는 상태다 — `resolveTaxYear`가 시드 없이는 거부한다. 단언의
     * 목적은 값이 아니라 **폴백이 무게를 진다는 사실**이다.)
     */
    expect(
      selectableYears({ seededYears: [], year: 2030, taxLawYear: 2026 }, 2026),
    ).toEqual([2026, 2030])
  })

  it('★ `seededYears`가 내림차순이면 구간이 사라진다 — 전제를 케이스로 고정한다', () => {
    /*
     * ★ **이 함수는 정렬을 검사하지 않는다.** `seeded[0]`을 하한, 마지막 원소를 상한으로
     * 읽으므로 내림차순에서는 `first > last`가 되어 루프가 0회 돌고 **시드된 연도가
     * 선택지에서 조용히 사라진다**(오류 없이 낱개 하나만 남는다).
     *
     * 그 정렬은 조회 계층이 보장한다 — `resolveTaxYear`가 질의의 `order`에 기대지 않고
     * 스스로 정렬하며 그 이유를 주석으로 적는다. **그런데 이 모듈을 순수 모듈로 뗀 이유가
     * 「계약 없이 검증된다」이므로, 전제가 계약 쪽에만 있으면 이 함수의 검증 범위 밖이다.**
     * 그래서 그 성질을 여기에 값으로 고정한다 — 정렬 보장이 사라지는 날 이 케이스가
     * 「구간이 붕괴한다」를 문서화된 사실로 보여 준다(방어를 추가하는 것은 별 판단이며,
     * 지금 추가하면 계약이 이미 보장하는 것을 두 곳에서 하게 된다).
     */
    expect(
      selectableYears(
        { seededYears: [2027, 2026], year: 2026, taxLawYear: 2026 },
        2026,
      ),
    ).toEqual([2026])
  })
})
